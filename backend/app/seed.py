"""Idempotent seed with synthetic content only.

Names, emails, chat titles and message text are invented for this repository. No
row from any real account, and none of the chat titles observed in the reference
UI, appears here.
"""

from datetime import datetime, timedelta, timezone
from uuid import uuid4

from sqlalchemy import func, select
from sqlalchemy.orm import Session

from .models import Conversation, Message, Setting, User
from .security import hash_password

DEMO_EMAIL = "demo@example.com"
DEMO_PASSWORD = "demo-password-1"

_CHATS = [
    (
        "Weeknight dinner rotation",
        [
            ("user", "Give me four dinners I can cook in under 30 minutes."),
            (
                "model",
                "Four that hold up on a weeknight: a bean and greens skillet, "
                "lemon pasta with whatever cheese is left, sheet-pan chicken with "
                "root vegetables, and a lentil soup you can double.\n\n"
                "This reply is generated by the reconstructed backend.",
            ),
        ],
    ),
    (
        "Explaining a merge conflict",
        [("user", "How do I read a merge conflict without panicking?")],
    ),
    (
        "Notes into a status update",
        [
            ("user", "Turn three bullet points into a short status update."),
            ("model", "Here is a first pass in three sentences, one per bullet."),
        ],
    ),
]


def seed(db: Session) -> None:
    if db.scalar(select(func.count()).select_from(User)):
        return

    user = User(
        id=uuid4().hex,
        email=DEMO_EMAIL,
        name="Demo Person",
        password_hash=hash_password(DEMO_PASSWORD),
    )
    db.add(user)
    db.add(Setting(user_id=user.id))

    now = datetime.now(timezone.utc)
    for index, (title, turns) in enumerate(_CHATS):
        convo = Conversation(
            id=uuid4().hex,
            user_id=user.id,
            title=title,
            pinned=index == 0,
            created_at=now - timedelta(days=index + 1),
            updated_at=now - timedelta(hours=index + 1),
        )
        db.add(convo)
        for ordinal, (role, text) in enumerate(turns):
            db.add(
                Message(
                    id=uuid4().hex,
                    conversation_id=convo.id,
                    role=role,
                    text=text,
                    ordinal=ordinal,
                )
            )
    db.commit()


def seed_if_empty(db: Session) -> None:
    seed(db)
